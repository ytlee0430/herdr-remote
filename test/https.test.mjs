import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { WebSocket } from 'ws';
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));

test('HTTPS deployment pins browser origin and issues Secure login/logout cookies', { timeout: 10000 }, async t => {
  const dir = mkdtempSync(join(tmpdir(), 'herdr-https-'));
  const credentials = join(dir, 'credentials.json');
  writeFileSync(credentials, JSON.stringify({ browserPassword: 'synthetic-browser', clientToken: 'synthetic-bridge' }), { mode: 0o600 });
  const origin = 'https://relay.example.com';
  const server = spawn(process.execPath, ['relay.mjs'], { env: { ...process.env, HOST: '127.0.0.1', PORT: '0', PUBLIC_ORIGIN: origin, CREDENTIALS_FILE: credentials } });
  let logs = '';
  server.stdout.on('data', chunk => logs += chunk);
  server.stderr.on('data', chunk => logs += chunk);
  t.after(async () => { server.kill(); await Promise.race([once(server, 'exit'), delay(1000)]); rmSync(dir, { recursive: true, force: true }); });
  for (let i = 0; i < 100 && !/listening on (\d+)/.test(logs); i++) await delay(20);
  assert.match(logs, /listening on (\d+)/);
  const base = `http://127.0.0.1:${/listening on (\d+)/.exec(logs)[1]}`;
  const login = Origin => fetch(base + '/api/login', { method: 'POST', headers: { Origin }, body: JSON.stringify({ password: 'synthetic-browser' }) });
  assert.equal((await login(base)).status, 403);
  assert.equal((await login('https://wrong.example.com')).status, 403);
  const loggedIn = await login(origin);
  assert.equal(loggedIn.status, 200);
  assert.match(loggedIn.headers.get('set-cookie'), /; Secure/);
  const cookie = loggedIn.headers.get('set-cookie').split(';')[0];
  const registered = await fetch(base + '/api/client/register', { method: 'POST', headers: { Authorization: 'Bearer synthetic-bridge' }, body: JSON.stringify({ id: 'fixture', capabilities: ['mobile-v1'] }) });
  assert.equal(registered.status, 200);
  const wrong = new WebSocket(base.replace('http:', 'ws:') + '/terminal?id=fixture&mode=mobile', { headers: { Cookie: cookie, Origin: base } });
  wrong.on('error', () => {});
  const rejection = await new Promise(resolve => wrong.on('unexpected-response', (_, res) => { res.resume(); wrong.terminate(); resolve(res.statusCode); }));
  assert.equal(rejection, 401);
  const ws = new WebSocket(base.replace('http:', 'ws:') + '/terminal?id=fixture&mode=mobile', { headers: { Cookie: cookie, Origin: origin } });
  t.after(() => ws.terminate());
  await once(ws, 'open');
  const closed = once(ws, 'close');
  const logout = await fetch(base + '/api/logout', { method: 'POST', headers: { Cookie: cookie, Origin: origin } });
  assert.equal(logout.status, 200);
  assert.match(logout.headers.get('set-cookie'), /Max-Age=0; Secure/);
  await closed;
  assert.equal((await fetch(base + '/api/clients', { headers: { Cookie: cookie } })).status, 401);
});
